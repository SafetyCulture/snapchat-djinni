class SwiftGenerator(spec: Spec) extends Generator(spec) {

  val marshal = new SwiftMarshal(spec)

  // The option is a C++ namespace; Swift calls it with dots, or without a prefix when empty
  private val swiftxxPrefix = {
    val ns = spec.swiftxxNamespace.replace("::", ".")
    if (ns.isEmpty) "" else ns + "."
  }

  // The support types that the public API names live in DjinniSupportCore.
  private val coreSupportModule = "DjinniSupportCore"

  // DjinniSupport holds the C++ layer, so the generated module never names it in a public declaration.
  private def isCppLayerModule(module: String): Boolean =
    module == "DjinniSupport" || module == spec.swiftxxBaseLibModule || module == spec.swiftModule + "Cxx"

  // The two C++ glue modules are implementation details of the generated module when the option is on.
  // A public import that no public declaration uses is a warning, so the level follows the declarations of the file.
  private def importLine(module: String, publicLevel: Boolean): String =
    if (spec.swiftCxxFreeApi) {
      if (publicLevel && !isCppLayerModule(module)) s"public import $module" else s"internal import $module"
    }
    else if (spec.swiftInternalCxxImports && (module == spec.swiftModule + "Cxx" || module == spec.swiftxxBaseLibModule)) s"internal import $module"
    else s"import $module"

  // With --swift-cxx-free-api a marshaller names C++ types, so it stays internal to the generated module.
  private def publicMarshaller: String = if (spec.swiftCxxFreeApi) "" else "public "

  // The body names a type of DjinniSupportCore outside a doc comment. An unused public import is a warning, and the doc
  // comment of an async wrapper names the module.
  private def namesCoreModule(body: String): Boolean =
    body.split('\n').exists(line => line.contains(coreSupportModule + ".") && !line.trim.startsWith("*"))

  // DjinniSupportCore is imported only when a declaration names its types, because an unused public import is a warning.
  private def importModules(refs: Iterable[String], namesCore: Boolean): Seq[String] = {
    val modules = refs.toSet - coreSupportModule
    (if (namesCore) modules + coreSupportModule else modules).toSeq.sorted
  }

  // bodyRefs are the modules that only the internal declarations of the file use.
  def writeSwiftFile(ident: String, origin: String, refs: Iterable[String], bodyRefs: Iterable[String], f: IndentWriter => Unit) {
    val bodyModules = bodyRefs.toSet
    createFile(spec.swiftOutFolder.get, idSwift.ty(ident) + ".swift", (w: IndentWriter) => {
      w.wl("// AUTOGENERATED FILE - DO NOT MODIFY!")
      w.wl("// This file was generated by Djinni from " + origin)
      w.wl
      if (spec.swiftCxxFreeApi) {
        val body = new java.io.StringWriter()
        f(new IndentWriter(body))
        val text = body.toString
        val modules = importModules(refs ++ bodyModules, namesCoreModule(text))
        if (modules.nonEmpty) {
          modules.foreach(s => w.wl(importLine(s, publicLevel = !bodyModules.contains(s))))
          w.wl
        }
        w.w(text)
      } else {
        if (refs.nonEmpty) {
          refs.foreach(s => w.wl(importLine(s, publicLevel = true)))
          w.wl
        }
        f(w)
      }
    })
  }
  // publicRefs are the modules of the public declarations of the file, which are only the class of the static methods.
  def writeSwiftPrivateFile(ident: String, origin: String, refs: Iterable[String], publicRefs: Iterable[String], bodyRefs: Iterable[String], f: IndentWriter => Unit) {
    createFile(spec.swiftOutFolder.get, idSwift.ty(ident) + "+Private.swift", (w: IndentWriter) => {
      w.wl("// AUTOGENERATED FILE - DO NOT MODIFY!")
      w.wl("// This file was generated by Djinni from " + origin)
      w.wl
      if (spec.swiftCxxFreeApi) {
        val body = new java.io.StringWriter()
        f(new IndentWriter(body))
        val text = body.toString
        val namesCore = namesCoreModule(text)
        val publicModules = publicRefs.toSet.filter(m => m != coreSupportModule || namesCore)
        val modules = importModules(refs ++ bodyRefs, namesCore)
        if (modules.nonEmpty) {
          modules.foreach(s => w.wl(importLine(s, publicModules.contains(s))))
          w.wl
        }
        w.w(text)
      } else {
        if (refs.nonEmpty) {
          refs.foreach(s => w.wl(importLine(s, publicLevel = true)))
          w.wl
        }
        f(w)
      }
    })
  }

  def writeFlagNone(w: IndentWriter, e: Enum, ident: IdentConverter, t: String) {
    for (o <- e.options.find(_.specialFlag == Some(Enum.SpecialFlag.NoFlags))) {
      writeDoc(w, o.doc)
      w.wl(s"public static let ${ident(o.ident.name)}: $t = []")
    }
  }
  def writeFlags(w: IndentWriter, e: Enum, ident: IdentConverter, t: String) {
    var shift = 0
    for (o <- normalEnumOptions(e)) {
      writeDoc(w, o.doc)
      w.wl(s"public static let ${ident(o.ident.name)} = $t(rawValue: 1 << $shift)")
      shift += 1
    }
  }
  def writeFlagAll(w: IndentWriter, e: Enum, ident: IdentConverter, t: String) {
    for (
      o <- e.options.find(_.specialFlag.contains(Enum.SpecialFlag.AllFlags))
    ) {
      writeDoc(w, o.doc)
      val all = normalEnumOptions(e)
          .map{case o => "."+ident(o.ident.name)}
          .mkString(", ")
      w.w(s"public static let ${ident(o.ident.name)}: $t = [${all}]")
    }
  }

  override def generateEnum(origin: String, ident: Ident, doc: Doc, e: Enum) {
    writeSwiftFile(ident, origin, List[String](), Nil, w => {
      val t = marshal.typename(ident, e)
      if (e.flags) {
        w.w(s"public struct $t: OptionSet, Hashable, Codable, Sendable").braced {
          w.wl("public let rawValue: Int32")
          w.wl("public init(rawValue: Int32) { self.rawValue = rawValue }")
          writeFlagNone(w, e, idSwift.enum, t)
          writeFlags(w, e, idSwift.enum, t)
          writeFlagAll(w, e, idSwift.enum, t)
        }
      } else {
        // A client switch must stay exhaustive when the generated module has library evolution
        val frozen = if (spec.swiftCxxFreeApi) "@frozen " else ""
        w.w(s"${frozen}public enum ${marshal.typename(ident, e)}: Int32, Codable, Sendable").braced {
          writeEnumOptions(w, e, idSwift.enum, "=", "case ", "")
        }
      }
    })
    val enumPrivateImports = if (spec.swiftPrivateInSameModule) List("DjinniSupport") else List("DjinniSupport", spec.swiftModule)
    writeSwiftPrivateFile(ident, origin, enumPrivateImports, Nil, Nil, w => {
      w.wl(s"${publicMarshaller}typealias ${marshal.typename(ident, e)}Marshaller = DjinniSupport.EnumMarshaller<${marshal.typename(ident, e)}>")
    })
  }

  // return the base type if tm is optional otherwise None
  private def optionalBase(tm: MExpr) : Option[MExpr] = {
    tm.base match {
      case MOptional => Some(tm.args.head)
      case _ => None
    }
  }

  class SwiftRefs(name: String) {
    var swiftImports = mutable.TreeSet[String]()
    // Modules that only the internal declarations of a public file use
    var bodyImports = mutable.TreeSet[String]()
    var privateImports = mutable.TreeSet[String]("DjinniSupport", "Foundation", spec.swiftxxBaseLibModule, spec.swiftModule + "Cxx")
    if (!spec.swiftPrivateInSameModule) {
      privateImports.add(spec.swiftModule)
    }
    // A public import that no public declaration uses is a warning, so the option adds Foundation only for its types.
    if (!spec.swiftCxxFreeApi) { swiftImports.add("Foundation") }
    def find(ty: TypeRef) { find(ty.resolved) }
    def find(tm: MExpr) {
      tm.args.foreach(find)
      find(tm.base)
    }
    def find(m: Meta) = {
      if (spec.swiftCxxFreeApi && (m == MDate || m == MBinary)) { swiftImports.add("Foundation") }
      for (r <- marshal.references(m, name)) r match {
        // don't import empty module name (e.g. types defined in stdlib) or same module as the current one
        case ImportRef(arg) =>
          // The same mapping as the type name, so the import matches the module that a signature names
          val module = m match {
            case e: MExtern => SwiftSupport.publicModule(spec.swiftCxxFreeApi, e.swift.module, e.swift.typename)
            case _ => arg
          }
          if (module.nonEmpty && module != spec.swiftModule) { swiftImports.add(module) }
        case PrivateImportRef(arg) => if (arg.nonEmpty && arg != spec.swiftModule) { privateImports.add(arg) }
        case _ =>
      }
    }
  }

  def generateSwiftConstants(w: IndentWriter, consts: Seq[Const]) = {

    def writeSwiftConst(w: IndentWriter, ty: TypeRef, v: Any): Unit = v match {
      case l: Long => w.w(l.toString)
      case d: Double => w.w(d.toString)
      case b: Boolean => w.w(if (b) "true" else "false")
      // The generator checks the string before it writes a file, so a problem here cannot happen
      case s: String => w.w(SwiftLiteral.convert(s).fold(message => throw GenerateException(message), literal => literal))
      case e: EnumValue =>  w.w(s"${marshal.typename(ty)}.${idSwift.enum(e)}")
      case v: ConstRef => w.w(idSwift.const(v))
      case z: Map[_, _] => { // Value is record
        val recordMdef = ty.resolved.base.asInstanceOf[MDef]
        val record = recordMdef.body.asInstanceOf[Record]
        val vMap = z.asInstanceOf[Map[String, Any]]
        w.wl(s"${marshal.typename(ty)}(")
        w.increase()
        // Use exact sequence
        val skipFirst = SkipFirst()
        for (f <- record.fields) {
          skipFirst {w.wl(",")}
          w.w(SwiftIdent.label(idSwift.field(f.ident)) + ":")
          writeSwiftConst(w, f.ty, vMap.apply(f.ident.name))
        }
        w.w(")")
        w.decrease()
      }
    }

    for (c <- consts) {
      writeDoc(w, c.doc)
      w.w(s"public static let ${idSwift.const(c.ident)}: ${marshal.fieldType(c.ty)} = ")
      writeSwiftConst(w, c.ty, c.value)
      w.wl
    }
  }

  def generateConformance(deriving: Set[Record.DerivingType.Value], sendable: String, prefix: String) = {
    // Equatable needs Hashable for a record in a set or as a map key
    val eq = if (deriving.contains(DerivingType.Eq)) "Equatable" else ""
    val hashable = if (deriving.contains(DerivingType.Hashable) || deriving.contains(DerivingType.Eq)) "Hashable" else ""
    val codable = if (deriving.contains(DerivingType.Codable)) "Codable" else ""
    // Qualified so a record named Error does not shadow the protocol
    val error = if (deriving.contains(DerivingType.Error)) "Swift.Error" else ""
    val conformance = Array(eq, hashable, codable, error, sendable).filter(_ != "")
    if (conformance.nonEmpty) prefix + conformance.mkString(", ") else ""
  }

  override def generateRecord(origin: String, ident: Ident, doc: Doc, params: Seq[TypeParam], r: Record) {
    val refs = new SwiftRefs(ident.name)
    r.fields.foreach(f => refs.find(f.ty))
    // A DataRef or a DataView makes the record not Sendable at all: there is no honest @unchecked claim for it.
    val sendable =
      if (r.fields.exists(f => marshal.holdsBuffer(f.ty.resolved))) ""
      else if (r.fields.forall(f => marshal.isSendable(f.ty.resolved))) "Sendable"
      else "@unchecked Sendable"
    val deriving = if (spec.swiftErrorType.contains(marshal.typename(ident, r))) r.derivingTypes + DerivingType.Error else r.derivingTypes
    val fieldKeyword = if (spec.swiftLegacyRecords) "var" else "let"
    writeSwiftFile(ident, origin, refs.swiftImports, Nil, w => {
      writeDoc(w, doc)
      w.w(s"public struct ${marshal.typename(ident, r)}${generateConformance(deriving, sendable, ": ")}").braced {
        generateSwiftConstants(w, r.consts)
        for (f <- r.fields) {
          writeDoc(w, f.doc)
          w.wl(s"public $fieldKeyword ${idSwift.field(f.ident)}: ${marshal.fqFieldType(f.ty)}")
        }
        val initParams = r.fields.map(f => s"${idSwift.field(f.ident)}: ${marshal.fqFieldType(f.ty)}").mkString(", ")
        w.wl
        w.wl(s"public init(${initParams})").braced {
          for (f <- r.fields) {
            w.wl(s"self.${idSwift.field(f.ident)} = ${idSwift.field(f.ident)}")
          }
        }
      }
    })
    writeSwiftPrivateFile(ident, origin, refs.privateImports, Nil, Nil, w => {
      w.w(s"${publicMarshaller}enum ${marshal.typename(ident, r)}Marshaller: DjinniSupport.Marshaller").braced {
        w.wl(s"${publicMarshaller}typealias SwiftType = ${marshal.fqTypename(ident, r)}")
        w.w(s"${publicMarshaller}static func fromCpp(_ c: djinni.swift.AnyValue) throws -> SwiftType").braced {
          // A field named p or djinni would hide the closure parameter or the C++ namespace in the closure
          val fields = r.fields.map(f => idSwift.field(f.ident))
          val locals = fields.map(name => if (SwiftIdent.reservedLocals.contains(name)) SwiftIdent.fresh(name, fields.toSet ++ SwiftIdent.reservedLocals) else name)
          w.wl("return try withUnsafePointer(to: c) { p in").nested {
            for (((f, local), i) <- r.fields.zip(locals).zipWithIndex) {
              val swiftExp = s"DjinniSupport.compositeMember(p, $i)"
              w.wl(s"let $local = try ${marshal.fromCpp(f.ty, swiftExp)}")
            }
            val members = r.fields.zip(locals).map { case (f, local) => s"${SwiftIdent.label(idSwift.field(f.ident))}: $local" }.mkString(", ")
            w.wl(s"return SwiftType(${members})")
          }
          w.wl("}")
        }
        w.w(s"${publicMarshaller}static func toCpp(_ s: SwiftType) throws -> djinni.swift.AnyValue").braced {
          if (r.fields.nonEmpty) {
            w.wl("var ret = djinni.swift.makeCompositeValue()")
            for (f <- r.fields) {
              val swiftExpr = s"s.${idSwift.field(f.ident)}"
              w.wl(s"try DjinniSupport.addMember(&ret, ${marshal.toCpp(f.ty,swiftExpr )})")
            }
            w.wl("return ret")
          } else {
            w.wl("return djinni.swift.makeCompositeValue()")
          }
        }
      }
    })
  }
  // The name of a parameter inside the method. A parameter named djinni would hide the C++ namespace that the body
  // uses, so it has another name inside the method and keeps its label.
  private def internalName(m: Interface.Method, p: Field): String = {
    val name = idSwift.local(p.ident)
    if (name == "djinni") SwiftIdent.fresh(name, m.params.map(q => idSwift.local(q.ident)).toSet) else name
  }

  private def paramList(m: Interface.Method): String = {
    // skip label for the first parameter
    val first = if (m.params.nonEmpty) "_ " else ""
    first + m.params.zipWithIndex.map { case (p, index) =>
      val label = idSwift.local(p.ident)
      val internal = internalName(m, p)
      val declared = if (index > 0 && internal != label) s"$label $internal" else internal
      s"$declared: ${marshal.fqParamType(p.ty)}"
    }.mkString(", ")
  }

  // The arguments of a call to the proxy, from a closure that runs on another queue.
  private def proxyArguments(m: Interface.Method): String = {
    m.params.view.zipWithIndex.map { case (p, index) =>
      val label = if (index == 0) "" else s"${SwiftIdent.label(idSwift.local(p.ident))}: "
      label + sendableValue(m, p)
    }.mkString(", ")
  }

  // A parameter inside a closure that runs on another queue: a value that is not Sendable crosses in a box.
  private def sendableValue(m: Interface.Method, p: Field): String =
    if (marshal.isSendableArgument(p.ty.resolved)) internalName(m, p) else s"_${SwiftIdent.plain(p.ident)}.value"

  private def writeSendableBoxes(w: IndentWriter, m: Interface.Method) {
    for (p <- m.params if !marshal.isSendableArgument(p.ty.resolved)) {
      w.wl(s"let _${SwiftIdent.plain(p.ident)} = DjinniSupport.UncheckedSendable(${internalName(m, p)})")
    }
  }

  // The boxes of writeSendableBoxes. A local in the same closure must not hide one of them.
  private def boxNames(m: Interface.Method): Set[String] =
    m.params.filter(p => !marshal.isSendableArgument(p.ty.resolved)).map(p => s"_${SwiftIdent.plain(p.ident)}").toSet

  // A local takes another name when an IDL parameter or a box has its name. A parameter named inst does not hide the
  // member that holds the C++ object.
  private def writeCppCall(w: IndentWriter, glue: String, m: Interface.Method, value: Field => String, boxes: Set[String] = Set()) {
    val params = m.params.map(p => idSwift.local(p.ident)).toSet
    val list = SwiftIdent.fresh("_params", params ++ boxes)
    val ret = SwiftIdent.fresh("ret", params ++ boxes)
    w.wl(s"var $list = djinni.swift.ParameterList()")
    if (!m.static) {
      w.wl(s"$list.addValue(${if (params.contains("inst")) "self.inst" else "inst"})")
    }
    for (p <- m.params) {
      w.wl(s"$list.addValue(try ${marshal.toCpp(p.ty, value(p))})")
    }
    w.wl(s"var $ret = $glue(&$list)")
    w.wl(s"try handleCppErrors(&$ret)")
    if (!m.ret.isEmpty) {
      w.wl(s"return try ${marshal.fromCpp(m.ret.get, ret)}")
    }
  }

  // Each file evaluates the queue expression once, in djinniAsyncQueue. The module name in front stops a member or a
  // parameter with the same name from hiding it.
  private def queueArguments: Seq[String] = spec.swiftAsyncQueue.map(_ => s"${spec.swiftModule}.djinniAsyncQueue").toSeq

  private def writeQueueConstant(w: IndentWriter) {
    spec.swiftAsyncQueue.foreach { expression =>
      w.wl(s"private let djinniAsyncQueue: Dispatch.DispatchQueue = $expression")
      w.wl
    }
  }

  private def helperCall(helper: String): String = {
    val arguments = errorType.map(e => s"$e.self").toSeq ++ queueArguments
    if (arguments.isEmpty) s"DjinniSupport.$helper" else s"DjinniSupport.$helper(${arguments.mkString(", ")})"
  }

  // The Swift type of the --swift-error-type record, with its module.
  private var errorType: Option[String] = None

  // The module of the --swift-error-type record, when the record is an extern type of another module.
  private var errorTypeModule: Option[String] = None

  // The IDL methods of each interface that get a synchronous form (--swift-sync-method).
  private var syncMethods: Map[String, Set[String]] = Map.empty

  override def generate(idl: Seq[TypeDecl]) {
    errorType = spec.swiftErrorType.map(name => idl.collectFirst {
      case td: InternTypeDecl if td.body.isInstanceOf[Record] && idSwift.ty(td.ident.name) == name => marshal.fqTypename(td.ident.name, td.body)
      case td: ExternTypeDecl if td.body.isInstanceOf[Record] && swiftBlock(td, "typename").contains(name) =>
        swiftBlock(td, "module").fold(name)(module => s"$module.$name")
    }.getOrElse(name))
    // A public signature that throws the error type names its module when the record comes from another module.
    errorTypeModule = spec.swiftErrorType.flatMap(name => idl.collectFirst {
      case td: ExternTypeDecl if td.body.isInstanceOf[Record] && swiftBlock(td, "typename").contains(name) =>
        swiftBlock(td, "module").filter(module => module.nonEmpty && module != spec.swiftModule)
    }.flatten)
    syncMethods = spec.swiftSyncMethods.flatMap(_.split("\\.", 2) match {
      case Array(interface, method) => Some((interface, method))
      case _ => None
    }).groupBy(_._1).map { case (interface, pairs) => interface -> pairs.map(_._2).toSet }
    super.generate(idl)
  }

  private def swiftBlock(td: ExternTypeDecl, key: String): Option[String] = td.properties.get("swift") match {
    case Some(block: java.util.Map[_, _]) => Option(block.get(key)).map(_.toString)
    case _ => None
  }

  private def typed(i: Interface, m: Interface.Method): Boolean = errorType.isDefined && SwiftErrorType.affected(i, m)

  // An outcome, also inside a future, gives its value and throws its error.
  private def returnsOutcome(m: Interface.Method): Boolean = m.ret.map(_.resolved).exists(r =>
    marshal.isOutcome(r) || (marshal.isFuture(r) && marshal.isOutcome(r.args.head)))

  private def returnsFuture(m: Interface.Method): Boolean = m.ret.map(_.resolved).exists(marshal.isFuture)

  // The type that a generated signature names for the result: the value that an async wrapper or a typed method
  // unwraps, and the type itself otherwise.
  private def signatureResult(i: Interface, m: Interface.Method, wrap: Boolean): Option[MExpr] = m.ret.map(_.resolved) match {
    case None => None
    case Some(tm) =>
      val outer = marshal.isFuture(tm) || marshal.isOutcome(tm)
      if (wrap && !typed(i, m) && outer) {
        // The wrapper returns the value of a future or of an outcome, and its caller handles the error
        Some(tm.args.head)
      } else if (typed(i, m) && outer) {
        // A typed method returns the value and throws the error type
        if (marshal.isFuture(tm) && marshal.isOutcome(tm.args.head)) Some(tm.args.head.args.head) else Some(tm.args.head)
      } else Some(tm)
  }

  // The return type of a method with the typed error: the value of an outcome or a future.
  private def typedReturnType(m: Interface.Method): String = m.ret.map(_.resolved) match {
    case Some(tm) if marshal.isFuture(tm) && marshal.isOutcome(tm.args.head) => marshal.fqParamType(tm.args.head.args.head)
    case Some(tm) if marshal.isFuture(tm) || marshal.isOutcome(tm) => marshal.fqParamType(tm.args.head)
    case _ => marshal.fqReturnType(m.ret)
  }

  // A closure with the glue call. The helper changes its errors into the error type, and an outcome gives its value.
  private def writeTypedCall(w: IndentWriter, m: Interface.Method, head: String, body: IndentWriter => Unit) {
    w.wl(s"$head {")
    w.nested { body(w) }
    w.wl("}" + (if (returnsOutcome(m)) ".get()" else ""))
  }

  // The arguments of a call that runs on the thread of the caller: the parameters, with no sendable box.
  private def directArguments(m: Interface.Method): String = {
    m.params.view.zipWithIndex.map { case (p, index) =>
      val label = if (index == 0) "" else s"${SwiftIdent.label(idSwift.local(p.ident))}: "
      label + internalName(m, p)
    }.mkString(", ")
  }

  // A listed method also gets a synchronous form. It calls C++ on the thread of the caller, so it suits a
  // registration that returns at once.
  private def writeSyncWrapperMethod(w: IndentWriter, m: Interface.Method) {
    w.wl
    val sentence = " The C++ call runs on the caller's thread and blocks it. Use this method for a registration that returns at once."
    writeMethodDoc(w, m, idSwift.local, if (m.doc.lines.isEmpty) Seq(sentence) else Seq("", sentence))
    w.w(s"public func ${SwiftSyncMethods.syncName(idSwift.method, m)}(${paramList(m)})")
    val ret = m.ret.map(_.resolved)
    errorType match {
      case Some(e) => w.w(s" throws($e) -> ${typedReturnType(m)}")
      case None if ret.exists(marshal.isOutcome) => w.w(s" throws -> ${marshal.fqParamType(ret.get.args.head)}")
      case None => w.w(s" throws -> ${marshal.fqReturnType(m.ret)}")
    }
    w.braced {
      val call = s"djinniProxy.${idSwift.method(m.ident)}(${directArguments(m)})"
      // An outcome gives its value and throws its error, as it does in the async form.
      val get = if (returnsOutcome(m)) ".get()" else ""
      errorType match {
        case Some(e) => w.wl(s"return try DjinniSupport.djinniTyped($e.self) { try $call }$get")
        case None => w.wl(s"return try $call$get")
      }
    }
  }

  private def writeAsyncWrapper(w: IndentWriter, ident: Ident, doc: Doc, i: Interface) {
    val name = marshal.typename(ident, i)
    val queue = spec.swiftAsyncQueue.fold(s"a new serial queue (`${SwiftSupport.callQueueModule(spec.swiftCxxFreeApi)}.djinniCallQueue()`)")(e => s"`$e`, which this file evaluates once")
    val cancelled = errorType.fold("CancellationError")(e => s"$e(cancellation:)")
    val contract = Seq(
      s" Each async method runs its blocking C++ call on $queue. Calls to one object can run at the same time.",
      s" A task that is already cancelled when a method starts throws $cancelled and does not call C++. A task that waits",
      s" for a C++ future resumes once, with the result or with $cancelled. The C++ future is not cancelled; its late result is dropped.")
    writeQueueConstant(w)
    writeDoc(w, Doc(if (doc.lines.isEmpty) contract else doc.lines ++ Seq("") ++ contract))
    w.w(s"public final class $name: @unchecked Sendable").braced {
      // Prefixed name: an IDL method named proxy must not collide with the storage
      w.wl(s"let djinniProxy: ${name}CppProxy")
      w.wl
      w.wl(s"init(proxy: ${name}CppProxy) { self.djinniProxy = proxy }")
      for (m <- i.methods.filter(!_.static)) {
        w.wl
        writeMethodDoc(w, m, idSwift.local)
        val call = s"djinniProxy.${idSwift.method(m.ident)}(${proxyArguments(m)})"
        val ret = m.ret.map(_.resolved)
        // With nonisolated(nonsending) by default, the wrapper would run on the actor of the caller and its result would cross a domain.
        w.w(s"@concurrent public func ${idSwift.method(m.ident)}(${paramList(m)}) async")
        errorType match {
          case Some(e) => w.w(s" throws($e) -> ${typedReturnType(m)}")
          case None if ret.exists(r => marshal.isOutcome(r) || marshal.isFuture(r)) => w.w(s" throws -> ${marshal.fqParamType(ret.get.args.head)}")
          case None => w.w(s" throws -> ${marshal.fqReturnType(m.ret)}")
        }
        w.braced {
          writeSendableBoxes(w, m)
          val capture = "[djinniProxy = self.djinniProxy] in"
          val helper = (returnsFuture(m), errorType.isDefined) match {
            case (true, true) => "djinniCallFutureTyped"
            case (true, false) => "djinniCallFuture"
            case (false, true) => "djinniCallTyped"
            case (false, false) => "djinniCall"
          }
          // Without the error type, the error of a future of an outcome stays in the Result value.
          val get = if (ret.exists(marshal.isOutcome) || (errorType.isDefined && returnsOutcome(m))) ".get()" else ""
          w.wl(s"return try await ${helperCall(helper)} { $capture try $call }$get")
        }
        if (syncMethods.getOrElse(ident.name, Set[String]()).contains(m.ident.name)) {
          writeSyncWrapperMethod(w, m)
        }
      }
    }
  }

  // The methods of the proxy throw DjinniError when C++ throws. The wrapper gives it to the caller, or changes it into the --swift-error-type value.
  private def writeWrappedCppProxy(w: IndentWriter, ident: Ident, i: Interface) {
    val name = marshal.typename(ident, i)
    w.w(s"final class ${name}CppProxy: DjinniSupport.CppProxy, @unchecked Sendable").braced {
      w.wl("init(_ inst: djinni.swift.AnyValue) { super.init(inst:inst) } ")
      for (m <- i.methods.filter(!_.static)) {
        w.w(s"func ${idSwift.method(m.ident)}(${paramList(m)}) throws -> ${marshal.fqReturnType(m.ret)}").braced {
          writeCppCall(w, s"${swiftxxPrefix}${name}_${SwiftIdent.plain(m.ident)}", m, internalName(m, _))
        }
      }
    }
  }

  override def generateInterface(origin: String, ident: Ident, doc: Doc, typeParams: Seq[TypeParam], i: Interface) {
    if (i.ext.objc && !i.ext.swift) {
      System.err.println(s"Warning: interface ${ident.name} has +o but not +sw. The generator makes no Swift proxy for it.")
    }
    val refs = new SwiftRefs(ident.name)
    i.methods.foreach(m => {
      m.params.foreach(p => refs.find(p.ty))
      m.ret.foreach(refs.find)
    })
    i.consts.foreach(c => {
      refs.find(c.ty)
    })
    // The wrapper takes the name of the protocol, so a wrapped interface has no protocol.
    val wrap = spec.swiftAsyncWrap.isDefined && i.ext.cpp && !i.ext.swift
    // The C++ proxy of an interface without the wrapper throws the error type too, so its file needs the module
    if (!wrap && i.ext.cpp && i.methods.exists(m => !m.static && typed(i, m))) {
      if (spec.swiftCxxFreeApi) errorTypeModule.foreach(refs.privateImports.add)
    }
    // The public API is the protocol, or the class of the async wrappers, and it holds the instance methods only.
    val apiRefs = new SwiftRefs(ident.name)
    i.methods.filter(!_.static).foreach(m => {
      m.params.foreach(p => apiRefs.find(p.ty))
      signatureResult(i, m, wrap).foreach(apiRefs.find)
      if (typed(i, m)) errorTypeModule.foreach(apiRefs.swiftImports.add)
    })
    // The class of the static methods is public, so its types need public imports in the private file.
    val staticsRefs = new SwiftRefs(ident.name)
    i.consts.foreach(c => staticsRefs.find(c.ty))
    i.methods.filter(m => m.static && m.lang.swift).foreach(m => {
      m.params.foreach(p => staticsRefs.find(p.ty))
      signatureResult(i, m, wrap = false).foreach(staticsRefs.find)
      if (typed(i, m)) errorTypeModule.foreach { module =>
        staticsRefs.swiftImports.add(module)
        // The private file holds the class of the static methods, and its imports decide the level
        if (spec.swiftCxxFreeApi) refs.privateImports.add(module)
      }
    })
    if (wrap) {
      refs.swiftImports.add("DjinniSupport")
      apiRefs.swiftImports.add("DjinniSupport")
      // The queue constant is private, and the expression of --swift-async-queue names DispatchQueue
      if (spec.swiftAsyncQueue.isDefined) { apiRefs.bodyImports.add("Dispatch") }
    }
    // With the option, a module that only a static method needs stays out of the public file
    val apiModules = if (spec.swiftCxxFreeApi) apiRefs.swiftImports else refs.swiftImports
    writeSwiftFile(ident, origin, apiModules, apiRefs.bodyImports, w => {
      if (wrap) {
        writeAsyncWrapper(w, ident, doc, i)
      } else {
        writeDoc(w, doc)
        w.w(s"public protocol ${marshal.typename(ident, i)}: AnyObject, Sendable").braced {
          for (m <- i.methods.filter(!_.static)) {
            writeMethodDoc(w, m, idSwift.local)
            w.w(s"func ${idSwift.method(m.ident)}(")
            // skip label for the first parameter
            if (m.params.nonEmpty) { w.w("_ ") }
            w.w(m.params.map(p => s"${idSwift.local(p.ident)}: ${marshal.fqParamType(p.ty)}").mkString(", "))
            if (typed(i, m)) {
              w.wl(s") throws(${errorType.get}) -> ${typedReturnType(m)}")
            } else {
              w.wl(s") throws -> ${marshal.fqReturnType(m.ret)}")
            }
          }
        }
      }
    })
    val interfaceBodyImports = if (spec.swiftAsyncQueue.isDefined && i.methods.exists(m => m.static && m.lang.swift && typed(i, m) && returnsFuture(m))) Seq("Dispatch") else Nil
    writeSwiftPrivateFile(ident, origin, refs.privateImports, staticsRefs.swiftImports, interfaceBodyImports, w => {
      if (i.methods.exists(m => m.static && m.lang.swift && typed(i, m) && returnsFuture(m))) {
        writeQueueConstant(w)
      }
      writeDoc(w, doc)
      // Define CppProxy class if interface is implemented in C++
      if (wrap) {
        writeWrappedCppProxy(w, ident, i)
      } else if (i.ext.cpp) {
        w.w(s"final class ${marshal.typename(ident, i)}CppProxy: DjinniSupport.CppProxy, ${marshal.fqTypename(ident, i)}, @unchecked Sendable").braced {
          w.wl("init(_ inst: djinni.swift.AnyValue) { super.init(inst:inst) } ")
          for (m <- i.methods.filter(!_.static)) {
            val glue = s"${swiftxxPrefix}${marshal.typename(ident, i)}_${SwiftIdent.plain(m.ident)}"
            if (typed(i, m)) {
              w.w(s"func ${idSwift.method(m.ident)}(${paramList(m)}) throws(${errorType.get}) -> ${typedReturnType(m)}").braced {
                writeTypedCall(w, m, s"return try DjinniSupport.djinniTyped(${errorType.get}.self)", writeCppCall(_, glue, m, internalName(m, _)))
              }
            } else {
              w.w(s"func ${idSwift.method(m.ident)}(${paramList(m)}) throws -> ${marshal.fqReturnType(m.ret)}").braced {
                writeCppCall(w, glue, m, internalName(m, _))
              }
            }
          }
        }
      }
      // Define the vtbl for protocol wrapper if interface is implemented in Swift
      val swiftProxyClassName = s"${marshal.typename(ident, i)}SwiftProxy"
      val swiftProxyVtbl = s"${SwiftIdent.plain(ident)}Methods"
      if (i.ext.swift) {
        w.wl(s"let $swiftProxyVtbl: Vtbl<${marshal.typename(ident, i)}> = [").nested {
          for (m <- i.methods.filter(!_.static)) {
            w.wl("{ inst, params, ret in").nested {
              for ((p, i) <- m.params.view.zipWithIndex) {
                val pi = s"DjinniSupport.parameter(params, $i)"
                w.wl(s"let _${SwiftIdent.plain(p.ident)} = try ${marshal.fromCpp(p.ty, pi)}")
              }
              val args = m.params.view.zipWithIndex.map{case (p, i) =>
                val label = if (i==0) "" else s"${SwiftIdent.label(idSwift.local(p.ident))}: "
                label + s"_${SwiftIdent.plain(p.ident)}"
              }.mkString(", ")
              val call = s"inst.${idSwift.method(m.ident)}(${args})"
              if (m.ret.isEmpty) {
                w.wl("try " + call)
              } else {
                w.wl(s"djinni.swift.setReturnValue(ret, try ${marshal.toCpp(m.ret.get, call)})")
              }
            }
            w.wl("},")
          }
        }
        w.wl("]")
        w.wl
      }
      // Define the marshaller
      if (wrap) {
        w.w(s"${publicMarshaller}enum ${marshal.typename(ident, i)}Marshaller: DjinniSupport.Marshaller").braced {
          w.wl(s"${publicMarshaller}typealias SwiftType = ${marshal.fqTypename(ident, i)}")
          w.w(s"${publicMarshaller}static func fromCpp(_ c: djinni.swift.AnyValue) throws -> SwiftType").braced {
            w.wl(s"return try cppWrapperToSwift(c, { ${marshal.typename(ident, i)}(proxy: ${marshal.typename(ident, i)}CppProxy(c)) })")
          }
          w.w(s"${publicMarshaller}static func toCpp(_ s: SwiftType) throws -> djinni.swift.AnyValue").braced {
            w.wl("return s.djinniProxy.inst")
          }
        }
      } else {
        w.w(s"${publicMarshaller}enum ${marshal.typename(ident, i)}Marshaller: DjinniSupport.Marshaller").braced {
          w.wl(s"${publicMarshaller}typealias SwiftType = ${marshal.fqTypename(ident, i)}")
          w.w(s"${publicMarshaller}static func fromCpp(_ c: djinni.swift.AnyValue) throws -> SwiftType").braced {
            val newProxyBlock = if (i.ext.cpp) {s"{ ${marshal.typename(ident, i)}CppProxy(c) as SwiftType }"} else {s"""{ throw DjinniError("${marshal.typename(ident, i)} has no C++ implementation: add +c to the interface") }"""}
            w.wl(s"return try cppInterfaceToSwift(c, ${newProxyBlock})")
          }
          w.w(s"${publicMarshaller}static func toCpp(_ s: SwiftType) throws -> djinni.swift.AnyValue").braced {
            val newProxyBlock = if (i.ext.swift) {s"{ try checkedProxy(${swiftxxPrefix}$swiftProxyClassName.make(ctxPtr(s as SwiftType, ${swiftProxyVtbl}), dispatcherProtocalCall)) }"} else {s"""{ throw DjinniError("${marshal.typename(ident, i)} has no Swift host implementation: add +sw to the interface") }"""}
            w.wl(s"return try swiftInterfaceToCpp(s, ${newProxyBlock})")
          }
        }
      }
      // Define static method stubs; the interface constants live on the same class
      val staticMethods = i.methods.filter(m => m.static && m.lang.swift)
      if (!staticMethods.isEmpty || !i.consts.isEmpty) {
        w.w(s"public class ${marshal.typename(ident, i)}_statics: @unchecked Sendable").braced {
          generateSwiftConstants(w, i.consts)
          for (m <- staticMethods) {
            val glue = s"${swiftxxPrefix}${marshal.typename(ident, i)}_${SwiftIdent.plain(m.ident)}"
            if (typed(i, m) && returnsFuture(m)) {
              // The C++ call blocks, so it runs on the queue of the async wrappers
              w.w(s"@concurrent public static func ${idSwift.method(m.ident)}(${paramList(m)}) async throws(${errorType.get}) -> ${typedReturnType(m)}").braced {
                writeSendableBoxes(w, m)
                writeTypedCall(w, m, s"return try await ${helperCall("djinniCallFutureTyped")}", writeCppCall(_, glue, m, sendableValue(m, _), boxNames(m)))
              }
            } else if (typed(i, m)) {
              w.w(s"public static func ${idSwift.method(m.ident)}(${paramList(m)}) throws(${errorType.get}) -> ${typedReturnType(m)}").braced {
                writeTypedCall(w, m, s"return try DjinniSupport.djinniTyped(${errorType.get}.self)", writeCppCall(_, glue, m, internalName(m, _)))
              }
            } else {
              w.w(s"public static func ${idSwift.method(m.ident)}(${paramList(m)}) throws -> ${marshal.fqReturnType(m.ret)}").braced {
                writeCppCall(w, glue, m, internalName(m, _))
              }
            }
          }
        }
      }
    })
  }
