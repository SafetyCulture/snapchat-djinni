package djinni

import generatorTools.{ImportRef, SkipFirst, Spec}

import djinni.ast.{Doc, Ident, Interface, Record, TypeParam, TypeRef}
import djinni.meta.{MExpr, Meta}
import djinni.writer.IndentWriter

import java.io.File
import scala.collection.mutable

class KMPAndroidGenerator(spec: Spec) extends Generator(spec) {
  val marshal = new KotlinMarshal(spec)
  val javaMarshal = new JavaMarshal(spec)

  // create androidMain directory
  val androidMainOut = new File(spec.kotlinOutFolder.get, "androidMain/kotlin")
  if (!androidMainOut.exists()) {
    androidMainOut.mkdirs()
  }

  /* helper class which assembles set of required imports for types used within a generated files */
  private class KMPAndroidRefs() {
    var kotlin: mutable.Set[String] = mutable.TreeSet[String]()

    def find(ty: TypeRef): Unit = {
      find(ty.resolved)
    }

    def find(tm: MExpr): Unit = {
      tm.args.foreach(find)
      find(tm.base)
    }

    def find(m: Meta): Unit = for (r <- marshal.references(m)) r match {
      case ImportRef(arg) => kotlin.add(arg)
      case _ =>
    }
  }

  def writeKotlinFile(ident: String, origin: String, refs: Iterable[String], f: IndentWriter => Unit) {
    createFile(androidMainOut, idKotlin.ty(ident) + ".kt", (w: IndentWriter) => {
      w.wl("// AUTOGENERATED FILE - DO NOT MODIFY!")
      w.wl("// This file was generated by Djinni from " + origin)
      w.wl
      spec.kotlinPackage.foreach(s => w.wl(s"package $s").wl)
      if (refs.nonEmpty) {
        refs.foreach(s => w.wl(s"import $s"))
        w.wl
      }
      f(w)
    })
  }

  override def generateInterface(origin: String, ident: Ident, doc: Doc, typeParams: Seq[TypeParam], i: Interface): Unit = {
    val refs = new KMPAndroidRefs()

    // find any required imports for all method parameters / return types
    i.methods.filterNot(_.static).map(m => {
      m.params.map(p => refs.find(p.ty))
      m.ret.foreach(refs.find)
    })

    // find any required imports for constant types
    i.consts.map(c => {
      refs.find(c.ty)
    })

    writeKotlinFile(ident.name, origin, refs.kotlin, w => {
      val commonInterfaceType = idKotlin.ty(ident.name)
      val javaInterfaceLocal = idKotlin.local(ident.name)
      val javaInterfaceType = javaMarshal.fqTypename(ident, i)

      // wrap the java generated interface in a class which conforms to the generated commonMain interface.
      w.w(s"class Android$commonInterfaceType(private val $javaInterfaceLocal: $javaInterfaceType): $commonInterfaceType").braced {
        val skipFirst = SkipFirst()
        for (m <- i.methods if !m.static) {
          val commonMainMethod = idKotlin.method(m.ident)
          val commonMainParams = m.params
            .map(p => s"${idKotlin.local(p.ident)}: ${marshal.paramType(p.ty)}")
            .mkString("(", ", ", ")")
          val commonMainReturn = marshal.returnType(m.ret)

          skipFirst { w.wl }

          /*  override fun method( $commonMainParams ): $commonMain_return {
           *    val ret = $javaInterfaceLocal.$javaMethod(
           *      mapped($commonMainParam),
           *      ...
           *    )
           *    return mapped(ret)
           *  }
           */
          w.w(s"override fun $commonMainMethod$commonMainParams: $commonMainReturn").braced {

          }
        }
      }
    })
  }

  override def generateEnum(origin: String, ident: Ident, doc: Doc, e: ast.Enum): Unit = {
    val refs = new KMPAndroidRefs()

    writeKotlinFile(ident.name, origin, refs.kotlin, w => {
      val kotlinEnum = idKotlin.ty(ident.name)
      val javaEnum = javaMarshal.fqTypename(ident, e)

      /* generate the toJava() method */
      w.w(s"fun $kotlinEnum.toJava(): $javaEnum").braced {
        w.w("return when(this)").braced {
          for (o <- e.options) {
            val kotlinOption = idKotlin.enum(o.ident)
            val javaOption = idJava.enum(o.ident)
            w.wl(s"$kotlinEnum.$kotlinOption -> $javaEnum.$javaOption")
          }
        }
      }

      w.wl

      /* generate the toKotlin() method */
      w.w(s"fun $javaEnum.toKotlin(): $kotlinEnum").braced {
        w.w("return when(this)").braced {
          for (o <- e.options) {
            val kotlinOption = idKotlin.enum(o.ident)
            val javaOption = idJava.enum(o.ident)
            w.wl(s"$javaEnum.$javaOption -> $kotlinEnum.$kotlinOption")
          }
        }
      }
    })
  }

  override def generateRecord(origin: String, ident: Ident, doc: Doc, params: Seq[TypeParam], r: Record): Unit = {
    /* noop */
  }
}
